/**
 * 주기 고리가 **인스턴스 하나에서만** 돌게 하는 자물쇠.
 *
 * 인스턴스를 둘 이상 띄우면 폴러와 예약 고리가 인스턴스마다 하나씩 돈다. 폴러는 같은 공지를
 * 두 번 잡아 알림을 두 번 쏘고, 예약 고리는 같은 예약을 두 번 보낸다. 저장은 `ON CONFLICT` 가
 * 받아 주지만 **나간 알림은 못 거둔다.**
 *
 * 회차를 시작하기 전에 자물쇠를 잡고, 못 잡으면 **기다리지 않고 그 회차를 건너뛴다.** 다음
 * 회차가 1분 뒤에 오고 그때 잡은 쪽이 밀린 것을 함께 처리한다. 기다리면 느린 회차 뒤로 줄이
 * 서고, 자물쇠를 든 인스턴스가 죽는 순간 그 줄이 한꺼번에 터진다.
 *
 * 코디네이터를 따로 안 들이는 이유는 **DB 가 이미 공유 자원**이기 때문이다. 자물쇠를 든
 * 인스턴스가 죽으면 연결이 끊기며 postgres 가 알아서 푼다.
 *
 * 결산 고리(`settlement.ts`)는 여기 안 든다. 그쪽은 판정을 프로세스 메모리에 들고 API 가 그
 * 값을 읽어서, 한 인스턴스만 재게 하면 나머지가 늘 `결산 아님` 을 내놓는다. 그 고리는 판정을
 * DB 로 옮긴 뒤에 잡아야 한다.
 */

/**
 * 회차 하나를 감싼다. 자물쇠를 못 잡으면 `run` 을 **안 부른다.**
 *
 * @param run 자물쇠를 잡았을 때 돌릴 회차
 */
export type RunExclusively = (run: () => Promise<void>) => Promise<void>

/** 아무도 안 막는다. 인스턴스가 하나뿐인 지금의 기본값이고 테스트가 쓰는 값이다. */
export const runAnyway: RunExclusively = (run) => run()

